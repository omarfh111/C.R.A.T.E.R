"""Pin a declared dependency group from pyproject.toml, without installing anything.

    python scripts/pin-python-deps.py --group onnx-local --platform win32 --output pins.txt
    pip-audit --no-deps --requirement pins.txt

`pip-audit` refuses an unpinned requirement, and installing the local ONNX group to audit it
would pull PyTorch, ONNX Runtime and the DirectML provider onto the runner. This resolves each
requirement to the newest release that satisfies it using the PyPI JSON metadata API, so the
heavy and GPU-only packages are audited at the versions a fresh install would actually choose
while nothing is downloaded or built.

Groups are `core` (pyproject `[project].dependencies`, what the model-free demo and the default
CI install) or the name of any entry in `[project.optional-dependencies]`. `--platform` selects
the value of `sys_platform` used to evaluate environment markers, so the Windows DirectML pin
and the portable CPU pin can both be audited from one Linux runner.
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import InvalidVersion, Version

PYPI_JSON = "https://pypi.org/pypi/{name}/json"
# Marker values for the target interpreter. Only the fields the project's markers use matter.
PYTHON_VERSION = "3.12"


def requirements_for(pyproject: dict, group: str) -> list[str]:
    project = pyproject.get("project", {})
    if group == "core":
        return list(project.get("dependencies", []))
    extras = project.get("optional-dependencies", {})
    if group not in extras:
        known = ", ".join(["core", *sorted(extras)])
        raise SystemExit(f"Unknown dependency group {group!r}. Known groups: {known}")
    return list(extras[group])


def applies(requirement: Requirement, platform: str) -> bool:
    if requirement.marker is None:
        return True
    return requirement.marker.evaluate(
        {
            "sys_platform": platform,
            "platform_system": {"win32": "Windows", "darwin": "Darwin"}.get(platform, "Linux"),
            "python_version": PYTHON_VERSION,
            "extra": "",
        },
    )


def newest_matching(requirement: Requirement) -> str:
    """Newest non-prerelease release of `requirement` that satisfies its specifier."""
    url = PYPI_JSON.format(name=requirement.name)
    try:
        with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed https host
            metadata = json.load(response)
    except (urllib.error.URLError, json.JSONDecodeError) as error:
        raise SystemExit(f"Could not read PyPI metadata for {requirement.name}: {error}") from error

    candidates: list[Version] = []
    for raw, files in metadata.get("releases", {}).items():
        if not files or all(file.get("yanked") for file in files):
            continue
        try:
            version = Version(raw)
        except InvalidVersion:
            continue
        if version.is_prerelease or version.is_devrelease:
            continue
        if version in requirement.specifier:
            candidates.append(version)
    if not candidates:
        raise SystemExit(f"No released version of {requirement.name} satisfies {requirement.specifier}")
    return str(max(candidates))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", required=True, help="'core' or an optional-dependencies name")
    parser.add_argument(
        "--platform",
        default=sys.platform,
        choices=("win32", "linux", "darwin"),
        help="sys_platform value used to evaluate environment markers",
    )
    parser.add_argument("--pyproject", type=Path, default=Path("pyproject.toml"))
    parser.add_argument("--output", type=Path, help="write the pinned requirements here")
    args = parser.parse_args(argv)

    pyproject = tomllib.loads(args.pyproject.read_text(encoding="utf-8"))
    declared = requirements_for(pyproject, args.group)

    lines = [
        f"# Generated by scripts/pin-python-deps.py from {args.pyproject.name}",
        f"# group={args.group} sys_platform={args.platform} python_version={PYTHON_VERSION}",
        "# Newest released version satisfying each declared specifier. Nothing was installed.",
    ]
    skipped: list[str] = []
    for raw in declared:
        requirement = Requirement(raw)
        if not applies(requirement, args.platform):
            skipped.append(raw)
            continue
        pinned = newest_matching(requirement)
        lines.append(f"{canonicalize_name(requirement.name)}=={pinned}")

    for raw in skipped:
        lines.append(f"# skipped on {args.platform}: {raw}")

    text = "\n".join(lines) + "\n"
    if args.output:
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote {args.output} for group {args.group} on {args.platform}")
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
