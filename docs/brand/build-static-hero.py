"""Regenerate the motion-free hero from the animated one.

Documentation tooling only: it touches nothing outside docs/brand/ and is not part of the
M1/M2/M3 runtime or CI. Run it after editing crater-readme-hero.svg.

    python docs/brand/build-static-hero.py          # rewrite crater-hero-static.svg
    python docs/brand/build-static-hero.py --check  # verify it is up to date, exit 1 if not
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BRAND = Path(__file__).resolve().parent
SOURCE = BRAND / "crater-readme-hero.svg"
TARGET = BRAND / "crater-hero-static.svg"

FONT_RULES = (
    "\n      .d { font-family: 'Space Grotesk', -apple-system, 'Segoe UI', Roboto, Helvetica,"
    " Arial, sans-serif; }"
    "\n      .m { font-family: 'IBM Plex Mono', ui-monospace, 'SF Mono', Menlo, Consolas,"
    " monospace; }\n    "
)
BANNER = "<!-- Generated by build-static-hero.py from crater-readme-hero.svg: identical artwork, every motion rule stripped. -->"


def build(source_text: str) -> str:
    """Strip every motion rule, keeping the artwork and the font declarations."""
    out, count = re.subn(r"<style>.*?</style>", "<style>" + FONT_RULES + "</style>", source_text, flags=re.S)
    if count != 1:
        raise SystemExit(f"expected exactly one <style> block in {SOURCE.name}, found {count}")
    out = re.sub(r'\s+style="animation-delay:[^"]*"', "", out)

    for leftover in ("animation", "@keyframes", "<script"):
        if leftover in out:
            raise SystemExit(f"{leftover!r} survived the strip; update build-static-hero.py")

    out = out.replace(
        '<desc id="heroDesc">',
        '<desc id="heroDesc">Motion-free variant of the C.R.A.T.E.R. hero, generated from '
        "crater-readme-hero.svg. ",
        1,
    )
    marker = "<!-- ============ background ============ -->"
    if marker not in out:
        raise SystemExit("background marker missing; update build-static-hero.py")
    return out.replace(marker, f"{BANNER}\n\n  {marker}", 1)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify only, do not write")
    args = parser.parse_args()

    expected = build(SOURCE.read_text(encoding="utf-8"))

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
        if current == expected:
            print(f"{TARGET.name} is up to date")
            return 0
        print(f"{TARGET.name} is stale; run: python docs/brand/build-static-hero.py", file=sys.stderr)
        return 1

    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name} ({len(expected.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
